// shortcut: 실제 기록이 아닌 모양만 비슷한 더미, FastAPI 연결 시 서버 기록으로 교체
export function historyFor(room) {
  if (roomHistory24h[room.id]) return roomHistory24h[room.id];
  const base = roomHistory24h['2-2'];
  return {
    co2: base.co2.map((v) => Math.round((v * room.sensor.co2) / 1180)),
    pm25: base.pm25.map((v) => Math.round((v * room.sensor.pm25) / 18)),
  };
}

